import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(new URL('../../apps/portal/package.json',import.meta.url));
const {chromium,expect}=require('@playwright/test');
assert.ok(process.env.NR_PORTAL_URL && process.env.NR_ACCOUNT && process.env.NR_PASSWORD,'Set NR_PORTAL_URL, NR_ACCOUNT and NR_PASSWORD for an authorized test environment');
const browser=await chromium.launch({headless:true,...(process.env.NR_CHROMIUM_PATH?{executablePath:process.env.NR_CHROMIUM_PATH}:{})});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1050}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.NR_PORTAL_URL.replace(/\/?$/,'/');
 await page.goto(base+'login');
 await page.getByLabel('Username or email',{exact:true}).fill(process.env.NR_ACCOUNT);
 await page.getByLabel('Password',{exact:true}).fill(process.env.NR_PASSWORD);
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await expect(page.getByRole('heading',{name:'总览',exact:true})).toBeVisible({timeout:30000});
 for(const name of ['网站概览','流量来源','页面表现','转化表现','自然搜索表现','关键词研究','内容机会','任务列表','数据连接','项目设置']) await expect(page.getByRole('link',{name,exact:true})).toBeVisible();
 await expect(page.getByRole('link',{name:'搜索概览',exact:true})).toHaveCount(0);
 for(const name of ['行动草案（即将推出）','效果复盘（即将推出）']) await expect(page.getByRole('button',{name,exact:true})).toBeDisabled();
 const menuIcons=await page.locator('[data-slot="sidebar"] a svg').evaluateAll(nodes=>nodes.map(n=>n.innerHTML));
 assert.ok(menuIcons.length>=11);assert.equal(new Set(menuIcons).size,menuIcons.length,'Each menu link needs a distinct icon');
 await page.getByRole('link',{name:'任务列表',exact:true}).click();
 await expect(page.getByRole('heading',{name:'任务列表',exact:true})).toBeVisible();
 await expect(page.getByLabel('分析数据来源')).toHaveCount(0);
 await page.evaluate(()=>sessionStorage.setItem('nr-analysis-mode-1','history'));
 await page.goto(base+'website/overview?days=28&data=history');
 await expect(page.getByRole('heading',{name:'网站概览',exact:true})).toBeVisible({timeout:30000});
 await expect(page.locator('.nr-provenance')).toContainText('数据更新至');
 await expect(page.locator('.nr-app')).not.toContainText('历史快照');
 await expect(page.locator('.nr-tabs')).toHaveCount(0);
 await page.getByLabel('分析周期',{exact:true}).selectOption('7');
 await expect(page.getByLabel('流量图表周期',{exact:true})).toHaveValue('7');
 await page.getByRole('button',{name:'查看全部 →',exact:true}).first().click();
 await expect(page).toHaveURL(/website\/sources.*days=7/);
 await expect(page.getByRole('heading',{name:'流量来源',exact:true})).toBeVisible();
 await expect(page.locator('.nr-metrics')).toHaveCount(0);
 await page.locator('tbody .nr-keyword').first().click();
 await expect(page.getByRole('dialog')).toContainText('会话');
 await page.getByRole('button',{name:'关闭详情',exact:true}).click();
 await page.goto(base+'website/pages?days=28');
 await expect(page.getByRole('heading',{name:'页面表现',exact:true})).toBeVisible({timeout:30000});
 await page.locator('tbody .nr-keyword').first().click();
 await expect(page.getByRole('dialog')).toContainText('关联搜索查询');
 await page.getByRole('button',{name:'关闭详情',exact:true}).click();
 // Screenshots may contain business data; do not write them into this repository.
 await page.goto(base+'seo-opportunities/performance?days=28');
 await expect(page.getByRole('heading',{name:'自然搜索表现',exact:true})).toBeVisible({timeout:30000});
 await expect(page.getByRole('heading',{name:'自然搜索点击趋势 · Google web',exact:true})).toBeVisible();
 await page.locator('tbody .nr-keyword').first().click();
 await expect(page.getByRole('dialog')).toContainText('规则分析');
 await page.getByRole('button',{name:'关闭详情',exact:true}).click();
 await page.goto(base+'seo-opportunities/opportunities?days=28');
 await expect(page.getByRole('heading',{name:'内容机会',exact:true})).toBeVisible({timeout:30000});
 await expect(page.getByRole('heading',{name:'待核查的内容机会',exact:true})).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 console.log('PASS connected-only data, period propagation, dedicated pages, source/page/keyword drawers, mobile, no runtime errors');
}finally{await browser.close();}
