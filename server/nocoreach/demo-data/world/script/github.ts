import { t, type Issue, type Pull, type Repository } from './types.js';

const issue = (
  title: [string, string],
  body: [string, string],
  labels: string[],
  author: string,
  opened: number,
  closed: number | undefined,
  comments: number,
  reactions: number,
): Issue => ({
  title: t(...title),
  body: t(...body),
  labels,
  author,
  opened,
  ...(closed !== undefined ? { closed } : {}),
  comments,
  reactions,
});
const discussion = (
  category: NonNullable<Issue['discussion']>['category'],
  answered: boolean,
  title: [string, string],
  body: [string, string],
  author: string,
  opened: number,
  comments: number,
  reactions: number,
): Issue => ({
  title: t(...title),
  body: t(...body),
  labels: [],
  author,
  opened,
  comments,
  reactions,
  discussion: { category, answered },
});
const pull = (
  title: [string, string],
  author: string,
  opened: number,
  end: { merged?: number; closed?: number },
  comments: number,
): Pull => ({ title: t(...title), author, opened, ...end, comments });

